#!/usr/bin/env python3
"""Builds the launcher icons, the start screen logo and the store icons from
assets/branding/icon_<variant>.svg (standard plus one per season).

    python3 tools/build_icons.py

Needs rsvg-convert (librsvg) for the PNGs. Writes:

    android/app/src/main/res/drawable/ic_launcher_foreground[_<season>].xml
    android/app/src/main/res/drawable/ic_launcher_monochrome.xml
    android/app/src/main/res/drawable/splash_logo.xml           (standard)
    android/app/src/main/res/mipmap-anydpi-v26/ic_launcher[_<season>].xml
    android/app/src/main/res/mipmap-<density>/ic_launcher[_<season>].png
    assets/branding/icon_512.png        (standard, rounded tile: README)
    assets/branding/store_icon_512.png  (standard, full square: Google Play)

The SVGs are drawn as an iOS-style tile: the 1024 square is the whole icon.
An adaptive icon shows only the middle 72 of its 108 dp, so the foreground
maps the 1024 square onto those 72 dp (viewport 1536, offset 256); the tile
colour becomes the background layer (@color/ic_launcher_background).

All variants share one drawing and differ only in colour. The Flutter logo
repeats the drawing (lib/core/widgets/app_logo.dart) and the colours
(lib/core/theme/logo_colors.dart, checked by logo_colors_test.dart); keep
the drawing in step by hand.
"""

import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRANDING = os.path.join(ROOT, "assets", "branding")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
NS = {"svg": "http://www.w3.org/2000/svg"}

VARIANTS = ["standard", "spring", "summer", "autumn", "winter"]
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

# Android 12+ masks a start screen icon without background to a circle of
# 2/3 of its 288 dp box; at 0.8 the drawing's corners stay inside it.
SPLASH_SCALE = 0.8

HEADER = "<!-- Generated by tools/build_icons.py from assets/branding/icon_{}.svg. -->\n"


def argb(color, opacity=1.0):
    """#RRGGBB (+ opacity) -> #AARRGGBB."""
    return "#{:02X}{}".format(round(opacity * 255), color.lstrip("#").upper())


def read(variant):
    tree = ET.parse(os.path.join(BRANDING, "icon_{}.svg".format(variant)))
    svg = tree.getroot()
    tile = svg.find("svg:rect", NS)
    grad = svg.find(".//svg:linearGradient", NS)
    clip = svg.find(".//svg:clipPath/svg:path", NS)
    group = svg.find("svg:g", NS)
    tx, ty = map(float, re.match(r"translate\((\S+) (\S+)\)", group.get("transform")).groups())
    photo = group.find("svg:path", NS)
    crayons = group.find("svg:g", NS).findall("svg:path", NS)
    outline = group.findall("svg:path", NS)[-1]
    xs, ys = zip(*[map(float, p) for p in re.findall(r"(-?[\d.]+) (-?[\d.]+)", photo.get("d"))])
    return {
        "tile": tile.get("fill"),
        "stops": [(s.get("offset"), s.get("stop-color")) for s in grad.findall("svg:stop", NS)],
        "box": (min(xs), min(ys), max(xs), max(ys)),  # gradient runs corner to corner
        "clip": clip.get("d"),
        "translate": (tx, ty),
        "photo": photo.get("d"),
        "crayons": [
            (c.get("d"), c.get("stroke"), c.get("stroke-width"), float(c.get("opacity", "1")))
            for c in crayons
        ],
        "outline": (outline.get("d"), outline.get("stroke"), outline.get("stroke-width")),
    }


def drawing(icon, indent, outline_color=None, crayons=True):
    """The drawing as vector drawable elements, in SVG coordinates."""
    pad = " " * indent
    tx, ty = icon["translate"]
    x0, y0, x1, y1 = icon["box"]
    out = ['{}<group android:translateX="{:g}" android:translateY="{:g}">'.format(pad, tx, ty)]
    p = pad + "    "
    if crayons:
        stops = "".join(
            '\n{}            <item android:offset="{}" android:color="{}" />'.format(p, o, argb(c))
            for o, c in icon["stops"]
        )
        out.append(
            '{p}<path android:pathData="{d}">\n'
            '{p}    <aapt:attr name="android:fillColor">\n'
            '{p}        <gradient android:type="linear" android:startX="{x0:g}" android:startY="{y0:g}"'
            ' android:endX="{x1:g}" android:endY="{y1:g}">{stops}\n'
            "{p}        </gradient>\n"
            "{p}    </aapt:attr>\n"
            "{p}</path>".format(p=p, d=icon["photo"], x0=x0, y0=y0, x1=x1, y1=y1, stops=stops)
        )
        out.append("{}<group>".format(p))
        out.append('{}    <clip-path android:pathData="{}" />'.format(p, icon["clip"]))
        for d, color, width, opacity in icon["crayons"]:
            out.append(
                '{p}    <path\n'
                '{p}        android:pathData="{d}"\n'
                '{p}        android:strokeColor="{c}"\n'
                '{p}        android:strokeWidth="{w}"\n'
                '{p}        android:strokeLineCap="round"\n'
                '{p}        android:strokeLineJoin="round" />'.format(p=p, d=d, c=argb(color, opacity), w=width)
            )
        out.append("{}</group>".format(p))
    d, color, width = icon["outline"]
    out.append(
        '{p}<path\n'
        '{p}    android:pathData="{d}"\n'
        '{p}    android:strokeColor="{c}"\n'
        '{p}    android:strokeWidth="{w}"\n'
        '{p}    android:strokeLineCap="round"\n'
        '{p}    android:strokeLineJoin="round" />'.format(p=p, d=d, c=outline_color or argb(color), w=width)
    )
    out.append("{}</group>".format(pad))
    return "\n".join(out)


def vector(size_dp, viewport, body, comment):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + comment
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="{s}dp"\n'
        '    android:height="{s}dp"\n'
        '    android:viewportWidth="{v}"\n'
        '    android:viewportHeight="{v}">\n'
        "{body}\n"
        "</vector>\n".format(s=size_dp, v=viewport, body=body)
    )


def adaptive_foreground(icon):
    """1024 tile -> the visible 72 of 108 dp."""
    return '    <group android:translateX="256" android:translateY="256">\n{}\n    </group>'.format(
        drawing(icon, 8)
    )


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def png(svg_path, out, size):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), svg_path, "-o", out], check=True)


def suffix(variant):
    return "" if variant == "standard" else "_" + variant


def main():
    icons = {v: read(v) for v in VARIANTS}
    tiles = {icons[v]["tile"] for v in VARIANTS}
    if len(tiles) != 1:
        sys.exit("All variants need the same tile colour (one launcher background): {}".format(tiles))

    for v, icon in icons.items():
        name = "ic_launcher_foreground" + suffix(v)
        write(
            os.path.join(RES, "drawable", name + ".xml"),
            vector(108, 1536, adaptive_foreground(icon), HEADER.format(v)),
        )
        write(
            os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher{}.xml".format(suffix(v))),
            '<?xml version="1.0" encoding="utf-8"?>\n'
            + HEADER.format(v)
            + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@color/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/{}" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            "</adaptive-icon>\n".format(name),
        )
        svg_path = os.path.join(BRANDING, "icon_{}.svg".format(v))
        for density, size in DENSITIES.items():
            png(svg_path, os.path.join(RES, "mipmap-" + density, "ic_launcher{}.png".format(suffix(v))), size)

    standard = icons["standard"]
    # Themed icons (Android 13+): only the line, tinted by the launcher.
    write(
        os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
        vector(
            108,
            1536,
            '    <group android:translateX="256" android:translateY="256">\n{}\n    </group>'.format(
                drawing(standard, 8, outline_color="#FF000000", crayons=False)
            ),
            HEADER.format("standard"),
        ),
    )
    # Start screen: the drawing without the tile, on paper; the line colour
    # follows light/dark (@color/logo_line).
    write(
        os.path.join(RES, "drawable", "splash_logo.xml"),
        vector(
            288,
            1024,
            '    <group android:pivotX="512" android:pivotY="512" android:scaleX="{s}" android:scaleY="{s}">\n'
            "{body}\n"
            "    </group>".format(s=SPLASH_SCALE, body=drawing(standard, 8, outline_color="@color/logo_line")),
            HEADER.format("standard")
            + "<!-- 288dp is Android 12+'s start screen icon without background; scaled\n"
            "     to {} so the drawing stays inside its 192dp circle. Same size and\n"
            "     place as AppLogo in StartSplash. -->\n".format(SPLASH_SCALE),
        ),
    )

    svg_path = os.path.join(BRANDING, "icon_standard.svg")
    png(svg_path, os.path.join(BRANDING, "icon_512.png"), 512)
    # Google Play masks the corners itself and wants a full square.
    with open(svg_path, encoding="utf-8") as f:
        square = re.sub(r'(<rect[^>]*?) rx="[^"]*"', r"\1", f.read(), count=1)
    with tempfile.TemporaryDirectory() as tmp:
        tmp_svg = os.path.join(tmp, "square.svg")
        with open(tmp_svg, "w", encoding="utf-8") as f:
            f.write(square)
        png(tmp_svg, os.path.join(BRANDING, "store_icon_512.png"), 512)


if __name__ == "__main__":
    main()
